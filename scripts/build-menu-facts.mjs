#!/usr/bin/env node
// Regenerates supabase/functions/_shared/menu-facts.js — the facts the menu
// renderer needs but cannot look up at render time.
//
// The renderer runs inside a Deno edge function. It has no filesystem (so it
// cannot measure a photo) and no access to the mobile app's repo (so it cannot
// read the authoritative dietary data). Both are therefore baked in here, from
// real sources, by this script:
//
//   PHOTO_DIMS      measured from the actual files in assets/menu-photos with
//                   `sips`. Gives the browser real aspect-ratio data so it can
//                   reserve space before the image decodes (less layout shift).
//
//   VEGETARIAN_PIDS the ONLY items the site is willing to call vegetarian.
//                   Taken from the app's lib/menu-data.ts (the authoritative
//                   menu), joined on the item half of the pid, and re-checked
//                   against each dish's own description — the same rule the app
//                   applies in lib/menu-data-integrity.ts. An item whose copy
//                   mentions meat never gets the badge, whatever the flag says.
//
// Run after adding menu photos or changing dietary data in the app repo:
//   node scripts/build-menu-facts.mjs
// Then regenerate the page:  node scripts/render-index.mjs
import { execFileSync } from 'node:child_process';
import { readdirSync, readFileSync, statSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const repo = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const APP_MENU = '/Users/osmanmohammed/github/shaahi-biryani-app/lib/menu-data.ts';
const PHOTO_DIR = 'assets/menu-photos';

// ── photo dimensions ────────────────────────────────────────────────
const dims = {};
for (const f of readdirSync(resolve(repo, PHOTO_DIR)).sort()) {
  if (f.startsWith('.')) continue;
  const abs = resolve(repo, PHOTO_DIR, f);
  if (!statSync(abs).isFile()) continue;
  const out = execFileSync('sips', ['-g', 'pixelWidth', '-g', 'pixelHeight', abs], { encoding: 'utf8' });
  const w = out.match(/pixelWidth:\s*(\d+)/)?.[1];
  const h = out.match(/pixelHeight:\s*(\d+)/)?.[1];
  if (w && h) dims[`${PHOTO_DIR}/${f}`] = [Number(w), Number(h)];
}

// ── verified vegetarian ─────────────────────────────────────────────
// Parse the app's generated MENU literal. It is plain JSON inside a TS file.
const src = readFileSync(APP_MENU, 'utf8');
const marker = 'export const MENU: MenuData =';
if (!src.includes(marker)) throw new Error(`${APP_MENU}: missing "${marker}"`);
const literal = src.slice(src.indexOf('{', src.indexOf(marker))).trim().replace(/;$/, '');
const MENU = JSON.parse(literal);

// Identical term list and word-boundary rule to the app's menu-data-integrity.ts.
// Keep the two in step: a dish the app refuses to call vegetarian must not be
// called vegetarian here either.
const MEAT_TERMS = ['meat', 'chicken', 'beef', 'goat', 'lamb', 'mutton', 'fish', 'shrimp',
  'prawn', 'seafood', 'tilapia', 'keema', 'gosht', 'kabab', 'boti'];
const MEAT = new RegExp(`\\b(${MEAT_TERMS.join('|')})`, 'i');

const pids = [];
const rejected = [];
for (const item of MENU.items) {
  if (item.isVegetarian !== true) continue;
  if (MEAT.test(`${item.description} ${item.name}`)) { rejected.push(item.id); continue; }
  for (const v of item.variants) pids.push(`${item.id}|${v.id}`);
}
pids.sort();

const body = `// GENERATED by scripts/build-menu-facts.mjs — do not edit by hand.
//
// Facts the menu renderer needs but cannot look up at render time: it runs in a
// Deno edge function with no filesystem and no access to the app's repo.
// Regenerate with:  node scripts/build-menu-facts.mjs

// Real pixel dimensions of every menu photo, measured from the files. Emitted as
// width/height so the browser can reserve layout space before the image decodes.
export const PHOTO_DIMS = ${JSON.stringify(dims, null, 1)};

// The only pids the site will mark vegetarian. Derived from the app's
// authoritative lib/menu-data.ts and re-checked against each dish's own
// description, so an item whose copy mentions meat is excluded no matter what
// the flag says.${rejected.length ? `\n// Excluded as self-contradictory: ${rejected.join(', ')}` : ''}
export const VEGETARIAN_PIDS = new Set(${JSON.stringify(pids, null, 1)});
`;

writeFileSync(resolve(repo, 'supabase/functions/_shared/menu-facts.js'), body);
console.log(`menu-facts.js — ${Object.keys(dims).length} photos measured, ` +
  `${pids.length} vegetarian pids from ${MENU.items.filter((i) => i.isVegetarian === true).length} flagged items` +
  (rejected.length ? `, ${rejected.length} rejected as contradictory` : ''));
