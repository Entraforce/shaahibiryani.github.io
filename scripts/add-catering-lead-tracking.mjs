// catering-<city>.html and wedding-catering.html; the contact form on index.html;
// hall.html; reserve.html) to our own Edge Functions, which record the request
// and send the emails (create-catering-lead -> catering_inquiries,
// submit-website-form -> website_messages). formsubmit.co stays in each form's
