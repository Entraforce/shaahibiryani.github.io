// Line-ending agnostic (these files mix CRLF/LF) — anchor on the gtag config
// call itself, then the next </script> close after it, whatever separates them.
const GTAG_ANCHOR_RE = /gtag\('config', 'G-3NJRL7V5NB'\);\s*<\/script>/;
const FORM_ID_RE = /id="(caterForm|contactForm|hallForm|reserveForm)"/;

// index.html carries its own attribution capture (window.shaahiAttribution);
// hall.html and reserve.html have no attribution capture (none before either).
// These get only the forms block.
const LEAD_ONLY = new Set(['index.html', 'hall.html', 'reserve.html']);

export function targetFiles() {
  const pages = readdirSync(repo).filter((f) => /^catering-.*\.html$/.test(f) || f === 'wedding-catering.html');
  return [...pages.sort(), ...LEAD_ONLY];
}

function insertAttribution(html) {
  if (html.includes(ATTRIB_MARKER_START)) return html;
  const m = GTAG_ANCHOR_RE.exec(html);
  if (!m) return null;
  const at = m.index + m[0].length;
  return html.slice(0, at) + '\n' + attribSnippet + html.slice(at);
}

function currentLeadBlock(html) {
  const a = html.indexOf(LEAD_MARKER_START);
  if (a === -1) return null;
  const b = html.indexOf(LEAD_MARKER_END, a);
  return b === -1 ? null : { a, b: b + LEAD_MARKER_END.length };
}

// Inserts the lead block, or replaces an older version of it in place.
function insertLeadTracking(html) {
  if (!FORM_ID_RE.test(html)) return null; // no website form on this page
  const cur = currentLeadBlock(html);
  const want = leadSnippet.trimEnd();
  if (cur) return html.slice(0, cur.a) + want + html.slice(cur.b);
  const idx = html.lastIndexOf('</body>');
  if (idx === -1) return null;
  return html.slice(0, idx) + leadSnippet + html.slice(idx);
}

function main() {
  const files = targetFiles();
  const updated = [];
  const alreadyOk = [];
  const failed = [];

  for (const file of files) {
    const path = resolve(repo, file);
    let html = readFileSync(path, 'utf8');
    const hadAttrib = LEAD_ONLY.has(file) || html.includes(ATTRIB_MARKER_START);
    const cur = currentLeadBlock(html);
    const hadLead = !!cur && html.slice(cur.a, cur.b) === leadSnippet.trimEnd();

    if (hadAttrib && hadLead) {
      alreadyOk.push(file);
      continue;
    }

    if (check) {
      failed.push(file);
      continue;
    }

    const withAttrib = LEAD_ONLY.has(file) ? html : insertAttribution(html);
    if (withAttrib === null) { failed.push(`${file} (no gtag anchor)`); continue; }
    const withLead = insertLeadTracking(withAttrib);
    if (withLead === null) { failed.push(`${file} (no caterForm)`); continue; }

    writeFileSync(path, withLead);
    updated.push(file);
  }

  if (check) {
    if (failed.length === 0) {
      console.log(`Current catering lead tracking present on all ${files.length} pages with a catering form.`);
      return;
    }
    console.error(`Catering lead tracking MISSING on ${failed.length} page(s): ${failed.join(', ')}`);
    console.error('Run: node scripts/add-catering-lead-tracking.mjs');
    process.exit(1);
  }

  if (updated.length) console.log(`Wired ${updated.length} page(s): ${updated.join(', ')}`);
  if (alreadyOk.length) console.log(`Already present on ${alreadyOk.length} page(s) — left unchanged.`);
  if (failed.length) {
    console.error(`FAILED on ${failed.length} page(s): ${failed.join(', ')}`);
    process.exit(1);
  }
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) main();
